/// 영수증을 읽는 동안 보여줄 소 상식.
///
/// ## 왜 이게 있나
///
/// 예전엔 돌아가는 동그라미 아래에 `영수증을 읽는 중…` 한 줄만 있었다.
/// 한 장이면 5초, 여러 장이면 수십 초인데 그 동안 읽을 것이 없으면 사용자는
/// 화면을 내려놓고 다른 일을 한다. 돌아와서 다시 보면 또 기다림이다.
/// **기다리는 시간은 그대로여도 읽을 것이 있으면 짧게 느껴진다.**
///
/// ## 분량 규칙 — 5초 안에 다 읽혀야 한다
///
/// 한 장 읽는 데 보통 5초쯤 걸린다. 그 안에 못 읽을 길이면 매번 중간에
/// 끊기고, 끊기는 글은 안 읽는 글보다 더 답답하다. 그래서 **두 문장 ·
/// [triviaMaxLength]자 이하**로 못 박았다
/// (`test/reading_trivia_test.dart` 가 막는다).
///
/// 형식은 **사실 한 문장 + 왜 그런지 한 문장**이다. 사실만 적으면 "그래서?" 가
/// 남고, 이유까지 붙으면 그 자체로 끝난 글이 된다.
///
/// **말투는 존댓말이다** — 주석·문서는 평어체지만 이건 화면에 떠서 사용자에게
/// 하는 말이고, 앱의 다른 문구가 전부 존댓말이다("증빙이 없습니다."·"읽기가
/// 끝나면 [다시 찍기] 를 누를 수 있습니다."). 한 화면에서 말투가 갈리면
/// 상식 쪽이 남이 쓴 글처럼 읽힌다.
///
/// ## 사실만 적는다
///
/// 사내 앱이라 같은 글을 같은 사람이 수십 번 본다. 틀린 상식은 그만큼 반복해서
/// 박히고, 하필 우리가 소를 다루는 회사다. 그래서 들은 이야기(소의 위가 6개라는
/// 흔한 오해 같은 것)는 넣지 않았다 — 위는 네 개다. 새로 추가할 때도
/// **출처를 확인한 것만** 넣는다.
library;

import 'dart:math';

/// 한 꼭지의 최대 길이. 로딩 시간(약 5초) 안에 읽히는 분량이다.
const triviaMaxLength = 90;

/// 보여줄 꼭지들. 순서는 의미가 없다 — 섞어서 쓴다([shuffledTrivia]).
///
/// 늘려도 되지만 **길게 쓰지는 않는다.** 분량은 위 라이브러리 주석 참고.
const cowTrivia = <String>[
  '소의 위는 네 개입니다.\n사람이 못 쓰는 풀의 섬유질을 첫 번째 위에 사는 미생물이 대신 분해해 줍니다.',
  '소는 하루에 침을 100리터 넘게 흘립니다.\n위 속 미생물이 만든 산을 중화해 발효가 멈추지 않게 하기 위함입니다.',
  '소는 위턱에 앞니가 없습니다.\n단단한 잇몸에 혀로 풀을 감아 올린 다음 아래 앞니로 끊어 먹습니다.',
  '소의 코무늬는 사람 지문처럼 모두 다릅니다.\n그래서 코 사진으로 개체를 알아보는 기술이 쓰입니다.',
  '소는 눈이 양옆에 있어 시야각이 넓습니다.\n대신 거리감이 약해서 바닥 그림자도 구덩이로 보고 피합니다.',
  '소가 내뿜는 메탄은 방귀가 아니라 대부분 트림입니다.\n발효가 일어나는 혹위가 입 쪽에 가까워서입니다.',
  '젖소는 하루에 물을 100리터 넘게 마십니다.\n우유 1리터를 만드는 데 물이 서너 리터 드는 셈입니다.',
  '소는 눕는 시간이 줄면 우유 양이 먼저 떨어집니다.\n그래서 축사에서 눕는 자리를 중요하게 생각합니다.',
  '소도 친한 상대가 정해져 있습니다.\n짝을 떼어 놓으면 심장이 빨라지고 스트레스 호르몬이 올라갑니다.',
  '소는 사람 얼굴을 기억합니다.\n거칠게 다룬 사람을 기억해서 피하니 조심히 다뤄주십시오.',
  '한우는 원래 일 시키기 위해 기르는 소였습니다.\n1960년대까지 논밭을 갈았고, 고기소로 기른 역사는 50년이 조금 넘습니다.',
];

/// 섞은 사본을 돌려준다. **한 번 읽는 동안 같은 꼭지가 두 번 나오지 않게** 하려고
/// 매번 무작위로 뽑는 대신 섞어서 순서대로 쓴다 — 매번 뽑으면 열 꼭지가 있어도
/// 바로 다음에 같은 글이 또 나온다.
///
/// [random] 은 테스트에서 씨앗을 고정하기 위한 구멍이다.
List<String> shuffledTrivia([Random? random]) => [...cowTrivia]..shuffle(random ?? Random());
