/// 값을 사람이 한 번 더 봐야 하는 **정도**.
///
/// ## 왜 숫자를 그대로 안 보여주는가
///
/// OCR 은 항목별 확신도를 0.0~1.0 으로 돌려준다. 그 숫자를 화면에 찍으면
/// 사용자는 `0.42` 가 무슨 뜻인지 모른다 — 고쳐야 하는 값인지, 그냥 봐도
/// 되는 값인지 설명할 방법이 없다. 그래서 **할 일이 다른 단계**로 나눈다.
///
/// ## 왜 두 단계인가
///
/// 예전엔 0.7 을 기준으로 "자신 없음" 하나만 있었다. 그러니 `0.39` 와
/// `0.69` 가 똑같이 보였는데, 둘은 할 일이 다르다 — 앞쪽은 사실상 못 읽은
/// 것이라 값을 믿을 수 없고, 뒤쪽은 한 번 훑으면 된다.
///
/// 단계를 더 쪼개지 않는 이유는 **경고가 드물어야 쓸모 있기 때문**이다.
/// 절반이 노랗게 뜨면 아무도 안 본다.
library;

enum Certainty {
  /// 확신도가 없다 — 직접 친 값·PDF·OCR 실패.
  ///
  /// **표시하지 않는다.** 모르는 것을 틀렸다고 말하지 않는다.
  unknown,

  /// 모델이 읽었고 자신 있다. 표시하지 않는다.
  ok,

  /// 읽었는데 자신 없다. 한 번 보면 된다.
  check,

  /// 거의 못 읽었다. 값이 틀렸다고 보고 확인해야 한다.
  poor;

  /// 화면에 표식을 달아야 하는가.
  bool get needsAttention => this == Certainty.check || this == Certainty.poor;
}
